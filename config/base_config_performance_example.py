# =============================================================================
# 注意事项
# =============================================================================

# 1. 批量写入的限制
#    - 内存占用会增加（batch_size 越大，内存占用越高）
#    - 数据不会立即写入数据库（程序结束前会自动刷新）
#    - 整批数据可能因单条错误失败（已在代码中处理）

# 2. 缓存的限制
#    - 内存缓存在进程重启后丢失（可使用 Redis 持久化）
#    - 数据库数据被外部修改时可能不一致

# 3. 并发的限制
#    - 并发数过高可能触发平台限流
#    - 数据库连接池不足会导致连接等待
#    - 建议在测试环境先测试合适的并发数

# 4. 数据库性能
#    - 确保已添加必要的索引（参考 schema/optimize_comment_indexes.sql）
#    - 定期分析表和优化表（ANALYZE TABLE, OPTIMIZE TABLE）
#    - 监控慢查询日志


